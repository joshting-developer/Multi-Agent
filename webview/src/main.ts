import { createApp } from 'vue';
import App from './App.vue';
import SettingsApp from './SettingsApp.vue';
import './styles.css';
import { reportClientError } from './composables/useHost';
const app = createApp(document.getElementById('app')?.dataset.surface === 'settings' ? SettingsApp : App);
app.config.errorHandler = error => { reportClientError(error); console.error(error); };
window.addEventListener('error', event => reportClientError(event.error ?? event.message));
window.addEventListener('unhandledrejection', event => reportClientError(event.reason));
app.mount('#app');
